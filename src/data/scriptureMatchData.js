// ============= HELPER FUNCTIONS =============
export const shuffleArray = (array) => {
  const shuffled = [...array];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
};

// Get scripture pairs for a specific page
const getScripturePairsForPage = (page) => {
  switch(page) {
    case 1: return SCRIPTURE_PAIRS_PAGE_1;
    case 2: return SCRIPTURE_PAIRS_PAGE_2;
    case 3: return SCRIPTURE_PAIRS_PAGE_3;
    case 4: return SCRIPTURE_PAIRS_PAGE_4;
    case 5: return SCRIPTURE_PAIRS_PAGE_5;
    default: return SCRIPTURE_PAIRS_PAGE_1;
  }
};

// Get symbols for a specific page
const getSymbolsForPage = (page) => {
  switch(page) {
    case 1: return SYMBOLS_PAGE_1;
    case 2: return SYMBOLS_PAGE_2;
    case 3: return SYMBOLS_PAGE_3;
    case 4: return SYMBOLS_PAGE_4;
    case 5: return SYMBOLS_PAGE_5;
    default: return SYMBOLS_PAGE_1;
  }
};

// Get page number for a level
export const getPageForLevel = (level) => {
  const levelConfig = LEVELS.find(l => l.level === level);
  return levelConfig?.page || 1;
};

// Check if a page is unlocked based on completed levels
export const isPageUnlocked = (pageNum, unlockedLevels) => {
  const page = PAGES.find(p => p.page === pageNum);
  if (!page) return false;
  return !page.requiredToUnlock || unlockedLevels > page.requiredToUnlock;
};

// Generate cards for a level (uses page-specific content)
export const generateCards = (level) => {
  const config = LEVELS.find(l => l.level === level) || LEVELS[0];
  const page = config.page || 1;
  const numPairs = config.cards / 2;
  let cards = [];

  // Get page-specific content
  const scripturePairs = getScripturePairsForPage(page);
  const symbols = getSymbolsForPage(page);

  if (config.matchType === 'symbol_symbol') {
    const selectedSymbols = shuffleArray(symbols).slice(0, numPairs);
    selectedSymbols.forEach((symbol, idx) => {
      cards.push({
        id: `${symbol.id}-a-${idx}`,
        pairId: symbol.id,
        type: 'symbol',
        content: symbol.emoji,
        label: symbol.name
      });
      cards.push({
        id: `${symbol.id}-b-${idx}`,
        pairId: symbol.id,
        type: 'symbol',
        content: symbol.emoji,
        label: symbol.name
      });
    });
  } else if (config.matchType === 'verse_pair') {
    const selectedVerses = shuffleArray(scripturePairs).slice(0, numPairs);
    selectedVerses.forEach((verse, idx) => {
      cards.push({
        id: `${verse.id}-first-${idx}`,
        pairId: verse.id,
        type: 'verse_first',
        content: verse.firstHalf,
        reference: verse.reference
      });
      cards.push({
        id: `${verse.id}-second-${idx}`,
        pairId: verse.id,
        type: 'verse_second',
        content: verse.secondHalf,
        reference: verse.reference
      });
    });
  } else if (config.matchType === 'symbol_verse') {
    const selectedSymbols = shuffleArray(symbols).slice(0, numPairs);
    selectedSymbols.forEach((symbol, idx) => {
      cards.push({
        id: `${symbol.id}-sym-${idx}`,
        pairId: symbol.id,
        type: 'symbol',
        content: symbol.emoji,
        label: symbol.name
      });
      cards.push({
        id: `${symbol.id}-verse-${idx}`,
        pairId: symbol.id,
        type: 'symbol_verse',
        content: symbol.relatedVerse,
        reference: symbol.reference
      });
    });
  } else {
    // Mixed mode - combine different types
    const halfPairs = Math.floor(numPairs / 2);
    
    // Symbol-symbol pairs
    const selectedSymbols = shuffleArray(symbols).slice(0, halfPairs);
    selectedSymbols.forEach((symbol, idx) => {
      cards.push({
        id: `${symbol.id}-a-${idx}`,
        pairId: symbol.id,
        type: 'symbol',
        content: symbol.emoji,
        label: symbol.name
      });
      cards.push({
        id: `${symbol.id}-b-${idx}`,
        pairId: symbol.id,
        type: 'symbol',
        content: symbol.emoji,
        label: symbol.name
      });
    });
    
    // Verse pairs
    const verses = shuffleArray(scripturePairs).slice(0, numPairs - halfPairs);
    verses.forEach((verse, idx) => {
      cards.push({
        id: `${verse.id}-first-${idx}`,
        pairId: verse.id,
        type: 'verse_first',
        content: verse.firstHalf,
        reference: verse.reference
      });
      cards.push({
        id: `${verse.id}-second-${idx}`,
        pairId: verse.id,
        type: 'verse_second',
        content: verse.secondHalf,
        reference: verse.reference
      });
    });
  }

  return shuffleArray(cards);
};
